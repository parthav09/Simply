"""Rebuild offline expected decisions from an exact, separately supplied Gary-2 file.

Usage: python simulation/tests/build_gary2_parity.py /path/to/Gary-2/simulation/agents/llm.py
No network, Raylib, provider SDK, credentials or model calls are used.
"""
import ast
import hashlib
import json
import random
import sys
from pathlib import Path
from types import SimpleNamespace as State

COMMIT = '93a4d0dac630461cbbb1d3e6e07b156f0b1bb7a3'
BLOB = '5d65a5401417c780ef5055834e25f6e978d4e03b'


def build(path):
    source = Path(path).read_bytes()
    if hashlib.sha1(b'blob '+str(len(source)).encode()+b'\0'+source).hexdigest() != BLOB:
        raise ValueError('Expected the exact reviewed upstream file; do not update expected outputs from an unreviewed policy')
    tree = ast.parse(source)
    cls = next(node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == 'LLMAgent')
    methods = {'get_owned_product_names', 'get_remaining_targets', 'get_remaining_iterations',
        'get_adjacent_move_visit_counts', 'choose_less_visited_move', 'should_navigate_to_checkout',
        'get_checkout_direction_move', '_get_owned_product_ids', 'adjust_llm_action'}
    cls.decorator_list = []; cls.bases = []
    cls.body = [node for node in cls.body if isinstance(node, ast.FunctionDef) and node.name in methods]
    namespace = {'LLMAction': lambda action, product_id=None, reasoning='': State(action=action, product_id=product_id, reasoning=reasoning)}
    module = ast.Module(body=[ast.ImportFrom(module='__future__', names=[ast.alias(name='annotations')], level=0), cls], type_ignores=[])
    exec(compile(ast.fix_missing_locations(module), '<pinned-gary2-policy>', 'exec'), namespace)
    rng = random.Random(121); cases = []
    for number in range(400):
        agent = namespace['LLMAgent'](); agent.x = agent.y = 3
        agent.inventory = [State(product_id='owned', product_name='owned')] if number % 3 else []
        if number % 7 == 0:
            agent.inventory = [State(product_id='target', product_name='target')]
        agent.checked_out_items = []; agent.shopping_targets = ['target']; agent.max_iterations = 120
        agent.iteration_count = rng.choice([0, 60, 83, 84, 85, 100, 105, 110, 119])
        agent.position_visit_counts = {(2, 3): rng.randrange(4), (4, 3): rng.randrange(4), (3, 2): rng.randrange(4), (3, 4): rng.randrange(4)}
        products = rng.choice([[], ['target'], ['treat'], ['target', 'treat']])
        allowed = ['move_left', 'move_right', 'move_up', 'move_down']
        if number % 5 == 0:
            allowed.remove('move_right')
        if products:
            allowed.append('grab')
        if agent.inventory:
            allowed.append('remove')
        if agent.inventory and number % 4 == 0:
            allowed.append('checkout')
        state = State(allowed_actions=allowed, can_checkout='checkout' in allowed,
            grabbable_items=[State(product_id=product, product_name=product) for product in products],
            nearest_checkout=State(delta_x=5, delta_y=5))
        step = rng.choice(allowed); product_id = rng.choice(products+['owned']) if step == 'grab' else None
        out = agent.adjust_llm_action(namespace['LLMAction'](step, product_id), state)
        cases.append({'name': f'upstream-{number:03d}', 'proposal': {'step': step, 'product_id': product_id, 'reason': 'parity case'},
            'before': {'x': 3, 'y': 3, 'cart': [{'product_id': item.product_id, 'quantity': 1} for item in agent.inventory],
                'requirements': [{'product_id': 'target', 'quantity': 1}], 'allowed_steps': allowed, 'turn_budget': 120, 'turns_used': agent.iteration_count},
            'layout': {'checkout': [[8, 8]], 'shelves': [{'x': 3, 'y': 4, 'offsets': [[0, 0]], 'products': [{'id': product} for product in products]}] if products else []},
            'visits': [[list(cell), count] for cell, count in agent.position_visit_counts.items()], 'expected': [out.action, out.product_id]})
    return {'commit': COMMIT, 'source_blob_sha': BLOB,
        'source': f'https://github.com/ved-2004/Gary-2/blob/{COMMIT}/simulation/agents/llm.py',
        'source_sha256': hashlib.sha256(source).hexdigest(),
        'scope': 'Generated by executing pinned upstream adjust_llm_action and helpers. Common abstract states: one unit per target, checkout reach normalized. Quantity and checkout-phase differences are tested separately.',
        'cases': cases}


if __name__ == '__main__':
    result = build(sys.argv[1])
    (Path(__file__).parent/'fixtures/gary2-policy-parity.json').write_text(json.dumps(result, separators=(',', ':'))+'\n')
    print(f"Generated {len(result['cases'])} pinned upstream policy cases; no API calls.")
